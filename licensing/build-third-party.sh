#!/usr/bin/env bash
# THIRD_PARTY_LICENSES를 조립한다: 수동 서문(rhwp 본체·vendor, 원문 그대로) + cargo-about 생성분.
# 사용: licensing/build-third-party.sh <rhwp 기준 Cargo.toml 경로> > THIRD_PARTY_LICENSES
# 구성: 1~4 = rhwp(HWP 엔진) / 5~6 = office_oxide와 그 의존성(DOCX 엔진, crates/fmt-docx 그래프)
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
manifest="${1:-$root/third_party/rhwp/Cargo.toml}"
bar='================================================================================'
cat <<HDR
Sheetfly — THIRD_PARTY_LICENSES
Sheetfly itself: Copyright (c) 2026 Dongwook Kim — MIT License (see LICENSE).
The components below are third-party and keep their own licenses.

$bar
1. rhwp (git submodule: third_party/rhwp)
$bar
https://github.com/edwardkim/rhwp

HDR
cat "$root/licenses/rhwp-LICENSE-MIT.txt"
cat <<HDR

$bar
2. svg2pdf — vendored inside rhwp (third_party/rhwp/vendor/svg2pdf, patched by rhwp)
$bar
MIT OR Apache-2.0. Upstream files, verbatim:

--- LICENSE-MIT ---
HDR
cat "$root/licenses/svg2pdf-LICENSE-MIT.txt"
printf '\n--- LICENSE-APACHE ---\n'
cat "$root/licenses/svg2pdf-LICENSE-APACHE.txt"
printf '\n--- NOTICE ---\n'
cat "$root/licenses/svg2pdf-NOTICE.txt"
cat <<HDR

$bar
3. Algorithms ported into rhwp, and specifications it references (verbatim from rhwp's THIRD_PARTY_LICENSES.md)
$bar
HDR
cat "$root/licensing/ported-algorithms.txt"
cat <<HDR

$bar
4. Rust crates (generated by cargo-about)
$bar
HDR
RUSTUP_TOOLCHAIN="${RUSTUP_TOOLCHAIN:-1.93.1}" cargo about generate --locked --manifest-path "$manifest" -c "$root/licensing/about.toml" "$root/licensing/about.hbs"
cat <<HDR

$bar
5. office_oxide (git submodule: third_party/office_oxide) — DOCX reading engine
$bar
https://github.com/yfedoseev/office_oxide
Licensed MIT OR Apache-2.0 at the user's option; Sheetfly uses it under the MIT License. The code is used unmodified.
"OfficeOxide" and "office_oxide" are trademarks of Yury Fedoseev (see its TRADEMARKS.md); Sheetfly only states that it uses the library and is not affiliated with or endorsed by its author.
Upstream NOTICE, verbatim:

HDR
cat "$root/licenses/office_oxide-NOTICE.txt"
printf '\n--- LICENSE-MIT ---\n'
cat "$root/licenses/office_oxide-LICENSE-MIT.txt"
cat <<HDR

$bar
6. Rust crates of the DOCX engine (generated by cargo-about for crates/fmt-docx)
$bar
HDR
RUSTUP_TOOLCHAIN="${RUSTUP_TOOLCHAIN:-1.93.1}" cargo about generate --locked --manifest-path "$root/crates/fmt-docx/Cargo.toml" -c "$root/licensing/about.toml" "$root/licensing/about.hbs" \
  | sed 's#from the dependency graph of third_party/rhwp (default features)#from the dependency graph of crates/fmt-docx (which depends on third_party/office_oxide)#'
